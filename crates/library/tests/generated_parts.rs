//! The generated part families of the standard library (`components/`).
//!
//! Families such as headers and DIP packages come in many sizes that must
//! stay consistent, so they are described here once and written out as
//! ordinary part folders. This test fails when a generated folder on disk
//! differs from what this file produces. After changing this file, rewrite
//! the folders with:
//!
//! ```sh
//! PERFBOARD_REGENERATE_PARTS=1 cargo test -p perfboard-library --test generated_parts
//! ```
//!
//! Generated `component.toml` files start with [`HEADER`]; hand-written parts
//! in `components/` are left alone.

use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
};

use perfboard_core::{
    ComponentDefinition, ComponentKind, Keepout, LocalPos, PinDefinition, RectMm, Rotation,
    component::{AccessDirection, AccessRegion, COMPONENT_SCHEMA_VERSION},
};

const HEADER: &str =
    "# Generated by crates/library/tests/generated_parts.rs: edit that file, not this one.\n";
const PITCH: f64 = 2.54;
const REGENERATE: &str = "PERFBOARD_REGENERATE_PARTS";

/// One generated part folder.
struct Part {
    folder: String,
    definition: ComponentDefinition,
    readme: String,
}

/// The outline of a part's body, seen from above, in millimetres from the
/// origin hole. Holes whose centre lies inside it, other than the pins, are
/// occupied.
enum Outline {
    Rect(RectMm),
    /// Centre and diameter.
    Circle {
        x: f64,
        y: f64,
        diameter: f64,
    },
}

fn round(value: f64) -> f64 {
    (value * 1000.0).round() / 1000.0
}

fn pin(id: &str, number: &str, name: &str, x: i32, y: i32) -> PinDefinition {
    PinDefinition {
        id: id.into(),
        number: number.into(),
        name: name.into(),
        x,
        y,
        aliases: Vec::new(),
        functions: vec!["passive".into()],
    }
}

fn numbered_pin(number: usize, x: i32, y: i32) -> PinDefinition {
    pin(
        &format!("pin_{number}"),
        &number.to_string(),
        &format!("Pin {number}"),
        x,
        y,
    )
}

fn terminals(pitch_holes: i32) -> Vec<PinDefinition> {
    vec![
        pin("terminal_1", "1", "Terminal 1", 0, 0),
        pin("terminal_2", "2", "Terminal 2", pitch_holes, 0),
    ]
}

/// A rectangle `width` by `height` mm centred on a point given in holes.
fn centred(x_holes: f64, y_holes: f64, width: f64, height: f64) -> Outline {
    Outline::Rect(RectMm {
        x: round(x_holes * PITCH - width / 2.0),
        y: round(y_holes * PITCH - height / 2.0),
        width,
        height,
    })
}

fn circle(x_holes: f64, y_holes: f64, diameter: f64) -> Outline {
    Outline::Circle {
        x: x_holes * PITCH,
        y: y_holes * PITCH,
        diameter,
    }
}

impl Outline {
    fn body(&self) -> RectMm {
        match *self {
            Self::Rect(rect) => rect,
            Self::Circle { x, y, diameter } => RectMm {
                x: round(x - diameter / 2.0),
                y: round(y - diameter / 2.0),
                width: diameter,
                height: diameter,
            },
        }
    }

    fn covers(&self, hole: LocalPos) -> bool {
        const EPSILON: f64 = 1e-6;
        let (hx, hy) = (f64::from(hole.x) * PITCH, f64::from(hole.y) * PITCH);
        match *self {
            Self::Rect(rect) => {
                hx > rect.x + EPSILON
                    && hx < rect.x + rect.width - EPSILON
                    && hy > rect.y + EPSILON
                    && hy < rect.y + rect.height - EPSILON
            }
            Self::Circle { x, y, diameter } => (hx - x).hypot(hy - y) < diameter / 2.0 - EPSILON,
        }
    }
}

/// The holes under the body that are not pins, and keepouts covering them:
/// one per run of holes in a row, merged with identical runs in the rows
/// below.
fn coverage(
    outline: &Outline,
    pins: &[PinDefinition],
) -> (Vec<LocalPos>, Vec<(LocalPos, LocalPos)>) {
    let body = outline.body();
    #[allow(clippy::cast_possible_truncation)] // Part bodies span a few dozen holes.
    let span = |from: f64, length: f64| {
        ((from / PITCH).floor() as i32 - 1)..=(((from + length) / PITCH).ceil() as i32 + 1)
    };
    let pin_holes: BTreeSet<(i32, i32)> = pins.iter().map(|pin| (pin.x, pin.y)).collect();
    let mut occupied = Vec::new();
    let mut runs: Vec<(i32, i32, i32, i32)> = Vec::new(); // x0, x1, y0, y1
    for y in span(body.y, body.height) {
        let mut row = Vec::new();
        for x in span(body.x, body.width) {
            let hole = LocalPos { x, y };
            if !pin_holes.contains(&(x, y)) && outline.covers(hole) {
                occupied.push(hole);
                row.push(x);
            }
        }
        let mut start = 0;
        while start < row.len() {
            let mut end = start;
            while end + 1 < row.len() && row[end + 1] == row[end] + 1 {
                end += 1;
            }
            let (x0, x1) = (row[start], row[end]);
            match runs
                .iter_mut()
                .find(|run| run.0 == x0 && run.1 == x1 && run.3 == y - 1)
            {
                Some(run) => run.3 = y,
                None => runs.push((x0, x1, y, y)),
            }
            start = end + 1;
        }
    }
    let keepouts = runs
        .into_iter()
        .map(|(x0, x1, y0, y1)| (LocalPos { x: x0, y: y0 }, LocalPos { x: x1, y: y1 }))
        .collect();
    (occupied, keepouts)
}

struct Spec<'a> {
    folder: &'a str,
    name: &'a str,
    designator: &'a str,
    description: &'a str,
    pins: Vec<PinDefinition>,
    outline: Outline,
    access: Vec<AccessRegion>,
    readme: String,
}

fn part(spec: Spec<'_>) -> Part {
    let (occupied_holes, runs) = coverage(&spec.outline, &spec.pins);
    let keepouts = runs
        .iter()
        .map(|&(min, max)| Keepout {
            min,
            max,
            label: "Body".into(),
        })
        .collect::<Vec<_>>();
    Part {
        folder: spec.folder.into(),
        definition: ComponentDefinition {
            schema_version: COMPONENT_SCHEMA_VERSION,
            kind: ComponentKind::Standard,
            id: format!("dev.perfboard.{}", spec.folder),
            definition_version: "1.0.0".into(),
            name: spec.name.into(),
            designator: spec.designator.into(),
            description: spec.description.into(),
            origin_x: 0,
            origin_y: 0,
            body: spec.outline.body(),
            allowed_rotations: vec![
                Rotation::Deg0,
                Rotation::Deg90,
                Rotation::Deg180,
                Rotation::Deg270,
            ],
            pins: spec.pins,
            occupied_holes,
            wire_keepouts: keepouts.clone(),
            keepouts,
            access: spec.access,
            documentation: String::new(),
        },
        readme: spec.readme,
    }
}

fn readme(title: &str, paragraphs: &[&str]) -> String {
    let mut text = format!("# {title}\n");
    for paragraph in paragraphs {
        text.push('\n');
        text.push_str(paragraph);
        text.push('\n');
    }
    text
}

