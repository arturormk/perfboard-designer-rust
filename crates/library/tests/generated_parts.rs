fn dip_packages() -> Vec<Part> {
    let mut parts = Vec::new();
    for (pins, wide) in [
        (8, false),
        (14, false),
        (16, false),
        (18, false),
        (20, false),
        (28, false),
        (28, true),
        (40, true),
    ] {
        let rows = if wide { 6 } else { 3 };
        let per_side = pins / 2;
        let per_side_i32 = i32::try_from(per_side).unwrap();
        // Top view, notch on the left: pin 1 bottom left, counting
        // anticlockwise.
        let pin_list = (1..=pins)
            .map(|number| {
                let number_i32 = i32::try_from(number).unwrap();
                if number <= per_side {
                    numbered_pin(number, number_i32 - 1, rows)
                } else {
                    numbered_pin(number, 2 * per_side_i32 - number_i32, 0)
                }
            })
            .collect();
        let width = if wide { 13.7 } else { 6.35 };
        let spacing = if wide { "15.24" } else { "7.62" };
        let (folder, name) = if wide {
            (format!("dip-{pins}-wide"), format!("DIP-{pins}, wide"))
        } else {
            (format!("dip-{pins}"), format!("DIP-{pins}"))
        };
        parts.push(part(Spec {
            folder: &folder,
            name: &name,
            designator: "U",
            description: &format!(
                "Generic {pins}-pin dual in-line package or socket, rows {spacing} mm apart"
            ),
            pins: pin_list,
            outline: centred(
                f64::from(per_side_i32 - 1) / 2.0,
                f64::from(rows) / 2.0,
                f64::from(per_side_i32) * PITCH - 0.4,
                width,
            ),
            access: Vec::new(),
            readme: readme(
                &name,
                &[
                    &format!(
                        "A {pins}-pin dual in-line package, or its socket, with rows {spacing} mm apart. The holes between the rows are occupied."
                    ),
                    &format!(
                        "Seen from above with the notch on the left, pin 1 is bottom left at `(0, {rows})` and pins count anticlockwise, so pin {pins} is top left at `(0, 0)`. Pins are named by number; copy the part to the project to name them after a particular chip."
                    ),
                ],
            ),
        }));
    }
    parts
}

fn headers() -> Vec<Part> {
    let mut parts = Vec::new();
    for (rows, columns) in [
        (1, 2),
        (1, 3),
        (1, 4),
        (1, 5),
        (1, 6),
        (1, 7),
        (1, 8),
        (2, 3),
        (2, 5),
    ] {
        for (gender, plural, use_for) in [
            (
                "male",
                "pins",
                "jumpers, Dupont leads and modules that plug in",
            ),
            ("female", "sockets", "modules and boards with male pins"),
        ] {
            let count = rows * columns;
            // A double row is numbered like a ribbon cable: 1 2 / 3 4 / …
            let pin_list = (1..=count)
                .map(|number| {
                    let index = i32::try_from(number - 1).unwrap();
                    if rows == 1 {
                        numbered_pin(number, index, 0)
                    } else {
                        numbered_pin(number, index / 2, index % 2)
                    }
                })
                .collect();
            let size = format!("{rows}x{columns}");
            let name = format!("Header {size}, {gender}");
            let layout = if rows == 1 {
                "in a row from the origin".to_owned()
            } else {
                "like a ribbon cable: odd pins along the first row and even pins along the second, so pin 2 is beside pin 1".to_owned()
            };
            parts.push(part(Spec {
                folder: &format!("header-{size}-{gender}"),
                name: &name,
                designator: "J",
                description: &format!(
                    "Generic {gender} {size} header, {count} {plural} on the 2.54 mm pitch"
                ),
                pins: pin_list,
                outline: centred(
                    f64::from(i32::try_from(columns).unwrap() - 1) / 2.0,
                    f64::from(i32::try_from(rows).unwrap() - 1) / 2.0,
                    f64::from(i32::try_from(columns).unwrap()) * PITCH,
                    f64::from(i32::try_from(rows).unwrap()) * PITCH,
                ),
                access: Vec::new(),
                readme: readme(
                    &name,
                    &[
                        &format!(
                            "A {gender} pin header with {count} {plural} on the 2.54 mm pitch, for {use_for}."
                        ),
                        &format!("Pins are numbered {layout}."),
                    ],
                ),
            }));
        }
    }
    parts
}

